-- 080_fix_taipei_nova_club_name.sql
-- 訂正第十一分區最後一筆社名：「台北新心扶輪社」→「台北新星扶輪社」。
--
-- 079 migration 訂正排序時發現這筆社名跟使用者提供的官方出席率 Excel
-- 對不上（Excel 寫「台北新星社」），當下沒有把握就直接改名字，留給
-- 使用者確認。這輪使用者已確認正確名稱是「新星」。回頭查
-- 020_seed_club_directory_from_excel.sql 的「手動確認對應」註解，
-- 發現「新心」這個名稱本身就是先前一輪把 Excel 的「台北新星社」對應
-- 過去時猜錯的（020 當時把它當成別名處理，沒有人工覆核），這次
-- 用使用者的確認直接訂正回官方名稱，跟其他社一樣補上「扶輪社」
-- 全稱（「台北新星扶輪社」，不是 Excel 簡稱「台北新星社」，比照
-- 015/020 seed 對其他社的既有慣例）。這筆的聯絡 email
-- （taipeinova.rotary@gmail.com，見 020 seed）也帶有「nova」（新星），
-- side confirms 這次訂正方向是對的。
--
-- 用舊名稱精準比對才更新，找不到就不動，避免誤改到別的社。
-- ════════════════════════════════════════════

UPDATE clubs
SET name = '台北新星扶輪社'
WHERE name = '台北新心扶輪社' AND zone = '第十一分區';
