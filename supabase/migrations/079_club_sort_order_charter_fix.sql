-- 修正「地區通訊錄」各分區內的社團排序，改回依成立（創社）順序，
-- 不要是目前的英文字母/筆畫順序。
--
-- 根因：016_club_sort_order.sql 幫 clubs 加 sort_order 欄位時，是用
-- `ORDER BY name`（依社名排序）去初始化每一筆的值，把 015 這份
-- seed 資料原本已經照正確創社順序輸入好的順序打散了。用使用者提供
-- 的地區官方出席率 Excel（『2026-27年度出席率.xlsx』，各分區社團前面
-- 都有「分區-序號」的官方編號，例如「1-1台北社」「1-2台北錫口社」）
-- 逐一比對，發現 015 seed 原本輸入的順序在絕大多數分區都跟這份 Excel
-- 的官方編號一致（驗證了 Excel 編號＝創社順序），只有第七分區「翡翠
-- 扶輪社」跟「台北明門扶輪社」兩筆順序顛倒（015 打反了），這裡照
-- Excel 訂正。
--
-- 已知兩個這次沒處理、需要使用者之後確認的落差：
--  1. 第十一分區最後一筆，Excel 寫「台北新星社」，但 015 seed／目前
--     資料庫存的是「台北新心扶輪社」——兩個字不一樣（星 vs 心），
--     不確定是哪邊打錯，這裡沿用資料庫現有的名稱去比對（只調整
--     sort_order，不動名稱），正不正確要請使用者自己核對。
--  2. 第六分區 Excel 多一筆「台北集品社」（排在最後，第 11 筆），
--     015 seed 只有到第 10 筆，代表這可能是後來才創立、透過畫面
--     手動新增的社團，這次不知道它在資料庫裡實際存的名稱是不是
--     完全一樣，沒有把它列進這份訂正清單，維持它現有的 sort_order
--     不動——如果它目前不是排在本分區最後一位，需要使用者到「社團
--     總覽」確認實際名稱後再另外處理。
--
-- 用 name+zone 精準比對才更新，任何一筆對不上（例如社名跟這裡列的
-- 不完全一樣）就直接不動那一筆，不會錯改到別的社。
-- ════════════════════════════════════════════

